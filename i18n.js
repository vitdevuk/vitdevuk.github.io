  var FALLBACK = "en";
  var list = [];
  var byCode = {};

  function usable(lang) {
    return lang && typeof lang.code === "string" && lang.code.trim() !== "" &&
      typeof lang.name === "string" && lang.name.trim() !== "" &&
      lang.dict && typeof lang.dict === "object";
  }

  function add(lang) {
    if (!usable(lang)) return;
    var code = lang.code.trim();
    if (byCode[code]) return;
    var entry = {
      code: code,
      name: lang.name.trim(),
      dir: lang.dir === "rtl" ? "rtl" : "ltr",
      locale: lang.locale && String(lang.locale).trim() ? String(lang.locale).trim() : code,
      dict: lang.dict
    };
    byCode[code] = entry;
    list.push(entry);
  }

  MN_MAIN_LANGUAGES.forEach(add);
  (Array.isArray(MN_EXTRA_LANGUAGES) ? MN_EXTRA_LANGUAGES : []).forEach(add);

  function resolve(code) {
    return code && byCode[code] ? code : FALLBACK;
  }

  // Missing or empty keys fall back to English, then to the key itself.
  function t(code, key) {
    var lang = byCode[resolve(code)];
    var value = lang.dict[key];
    if (typeof value === "string" && value !== "") return value;
    value = byCode[FALLBACK].dict[key];
    if (typeof value === "string" && value !== "") return value;
    return key;
  }

  window.MN_I18N = {
    fallback: FALLBACK,
    languages: list.map(function (l) { return { code: l.code, name: l.name, dir: l.dir, locale: l.locale }; }),
    resolve: resolve,
    get: function (code) { return byCode[resolve(code)]; },
    t: t
  };
